def _describe_option(name: str, spec: dict[str, Any], default: object) -> list[str]:
    return [
        _cell(name),
        _cell(spec.get("type", "str")),
        _cell(spec.get("required", False)),
        _cell(spec.get("default", default)),
        _cell(spec.get("choices")) if spec.get("choices") else "—",
    ]


def render_roles() -> str:
    roles_dir = _edge_roles_dir()
    version = "unknown"
    manifest = roles_dir.parent / "MANIFEST.json"
    if manifest.is_file():
        version = json.loads(manifest.read_text(encoding="utf-8"))["collection_info"][
            "version"
        ]
    lines = [
        BANNER,
        "# Ansible role variables",
        "",
        f"Generated from **blitzecdn.edge {version}** — each role's",
        "`meta/argument_specs.yml` and `defaults/main.yml`. Roles validate these",
        "at the start of every run, so an unsupported value fails before the host",
        "is touched.",
        "",
        "Reference roles by their fully qualified name, for example",
        "`blitzecdn.edge.blitzecdn_nginx`. Set variables in the control plane's",
        "`ansible/inventory/group_vars/blitzecdn_edges.yml`. Ansible only",
        "auto-loads `group_vars` adjacent to the inventory file — a `group_vars/`",
        "directory anywhere else is silently ignored.",
        "",
    ]

    for role_dir in sorted(roles_dir.iterdir()):
        spec_file = role_dir / "meta/argument_specs.yml"
        if not spec_file.is_file():
            continue
        spec = yaml.safe_load(spec_file.read_text(encoding="utf-8")) or {}
        main = spec.get("argument_specs", {}).get("main", {})
        defaults_file = role_dir / "defaults/main.yml"
        defaults = (
            yaml.safe_load(defaults_file.read_text(encoding="utf-8")) or {}
            if defaults_file.is_file()
            else {}
        )

        lines.append(f"## `{role_dir.name}`")
        lines.append("")
        if main.get("short_description"):
            lines.extend([_text(main["short_description"]), ""])

        options = main.get("options", {})
        rows = [
            _describe_option(name, option or {}, defaults.get(name))
            for name, option in sorted(options.items())
        ]
        lines.append(_table(["Variable", "Type", "Required", "Default", "Choices"], rows))

        for name, option in sorted(options.items()):
            suboptions = (option or {}).get("options")
            if not suboptions:
                continue
            lines.append(f"### `{name}` element keys")
            lines.append("")
            lines.append(
                _table(
                    ["Key", "Type", "Required", "Default", "Choices"],
                    [
                        _describe_option(key, sub or {}, None)
                        for key, sub in sorted(suboptions.items())
                    ],
                )
            )

    return "\n".join(lines)


