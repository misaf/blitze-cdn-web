def build_openapi_schema() -> dict[str, Any]:
    """Build the app against throwaway settings and return its schema."""
    from blitzecdn.api import create_app
    from blitzecdn.config import Settings

    with tempfile.TemporaryDirectory() as raw:
        root = Path(raw)
        ansible = root / "ansible"
        (ansible / "playbooks").mkdir(parents=True)
        state = root / "state"
        settings = Settings(
            project_dir=root,
            state_dir=state,
            database_path=state / "control-plane.db",
            ansible_dir=ansible,
            inventory_path=ansible / "inventory/hosts.yml",
            playbook_path=ansible / "playbooks/edge.yml",
            generated_vars_path=state / "desired-state.yml",
            deployment_lock_path=state / "deployment.lock",
            certificate_dir=state / "certificates",
            acme_challenge_playbook_path=ansible / "playbooks/acme-challenge.yml",
        )
        return create_app(settings).openapi()


def render_api(schema: dict[str, Any]) -> str:
    lines = [
        BANNER,
        "# HTTP API",
        "",
        f"Generated from the OpenAPI schema of `{schema['info']['title']}` "
        f"v{schema['info']['version']}.",
        "",
        "Every route below except `GET /health` requires the `X-API-Key` header.",
        "Ten failed authentications from one client address within a minute return",
        "`429`. Deployment and rollback routes return `202 Accepted` with a queued",
        "record; poll `GET /v1/deployments/{id}` for the outcome.",
        "",
    ]

    for path, operations in sorted(schema.get("paths", {}).items()):
        for method, operation in sorted(operations.items()):
            lines.append(f"## `{method.upper()} {path}`")
            lines.append("")
            summary = operation.get("summary")
            description = operation.get("description")
            if description:
                lines.extend([_text(description), ""])
            elif summary:
                lines.extend([_text(summary), ""])

            parameters = operation.get("parameters", [])
            if parameters:
                rows = [
                    [
                        _cell(item.get("name")),
                        _cell(item.get("in")),
                        _cell(item.get("required", False)),
                        _cell(_schema_name(item.get("schema", {}))),
                        _text(item.get("description")) or "—",
                    ]
                    for item in parameters
                ]
                lines.append("**Parameters**")
                lines.append("")
                lines.append(
                    _table(["Name", "In", "Required", "Type", "Description"], rows)
                )

            body = operation.get("requestBody")
            if body:
                for media, media_type in body.get("content", {}).items():
                    name = _schema_name(media_type.get("schema", {}))
                    required = " (required)" if body.get("required") else ""
                    lines.append(f"**Request body**{required}: `{media}` → `{name}`")
                    lines.append("")

            responses = operation.get("responses", {})
            rows = [
                [
                    _cell(code),
                    _text(response.get("description")) or "—",
                    _cell(
                        _schema_name(
                            response.get("content", {})
                            .get("application/json", {})
                            .get("schema", {})
                        )
                    )
                    if response.get("content")
                    else "—",
                ]
                for code, response in sorted(responses.items())
            ]
            lines.append("**Responses**")
            lines.append("")
            lines.append(_table(["Status", "Description", "Body"], rows))

    schemas = schema.get("components", {}).get("schemas", {})
    if schemas:
        lines.extend(["## Models", ""])
        for name, model in sorted(schemas.items()):
            lines.append(f"### `{name}`")
            lines.append("")
            if model.get("description"):
                lines.extend([_text(model["description"]), ""])
            required = set(model.get("required", []))
            rows = [
                [
                    _cell(field),
                    _cell(_schema_name(definition)),
                    _cell(field in required),
                    _cell(definition.get("default"))
                    if "default" in definition
                    else "—",
                ]
                for field, definition in sorted(model.get("properties", {}).items())
            ]
            lines.append(_table(["Field", "Type", "Required", "Default"], rows))

    return "\n".join(lines)


