def _default_text(node: ast.expr) -> str:
    """Render a default expression from config.py as readable prose."""
    if isinstance(node, ast.Constant):
        return "—" if node.value is None else str(node.value)
    # Defaults are written as `root / 'ansible'` or `state / 'deployment.lock'`.
    if (
        isinstance(node, ast.BinOp)
        and isinstance(node.op, ast.Div)
        and isinstance(node.left, ast.Name)
        and isinstance(node.right, ast.Constant)
    ):
        prefix = {"root": "<project_dir>", "state": "<state_dir>"}.get(
            node.left.id, node.left.id
        )
        return f"{prefix}/{node.right.value}"
    return ast.unparse(node)


def _settings_constraints() -> dict[str, str]:
    from blitzecdn.config import Settings

    constraints: dict[str, str] = {}
    for name, field in Settings.model_fields.items():
        parts = []
        for item in field.metadata:
            for attribute, symbol in (("ge", "≥"), ("le", "≤")):
                if hasattr(item, attribute):
                    parts.append(f"{symbol} {getattr(item, attribute)}")
        if parts:
            constraints[name] = ", ".join(parts)
    return constraints


def render_configuration() -> str:
    """Pair each BLITZE_* variable with its TOML key by parsing config.py."""
    source = _control_plane_source().read_text(encoding="utf-8")
    tree = ast.parse(source)

    settings_class = next(
        node
        for node in tree.body
        if isinstance(node, ast.ClassDef) and node.name == "Settings"
    )

    paired: list[tuple[str, str, str]] = []
    bare: list[str] = []
    for node in ast.walk(settings_class):
        if not isinstance(node, ast.Call):
            continue
        func = node.func
        name = getattr(func, "id", None) or getattr(func, "attr", None)
        if name in {"value", "path_value"} and len(node.args) >= 3:
            first, second = node.args[0], node.args[1]
            if isinstance(first, ast.Constant) and isinstance(second, ast.Constant):
                paired.append(
                    (
                        str(first.value),
                        str(second.value),
                        _default_text(node.args[2]),
                    )
                )
        elif (
            name == "get"
            and node.args
            and isinstance(node.args[0], ast.Constant)
            and str(node.args[0].value).startswith("BLITZE_")
        ):
            bare.append(str(node.args[0].value))

    constraints = _settings_constraints()
    rows = [
        [
            _cell(env),
            _cell(f"[blitzecdn].{toml_key}"),
            _cell(default) if default != "—" else "—",
            constraints.get(toml_key, "—"),
        ]
        for env, toml_key, default in sorted(set(paired))
    ]
    # Secrets get their own table below; do not repeat them.
    documented = {env for env, _, _ in paired} | {"BLITZE_API_KEY", "BLITZE_API_KEYS"}

    lines = [
        BANNER,
        "# Configuration",
        "",
        "Generated by parsing `Settings.from_environment` in",
        "`src/blitzecdn/config.py`, so this table cannot drift from the code that",
        "reads it.",
        "",
        "Precedence: environment variable, then the matching key in",
        "`blitzecdn.toml`, then the default. Relative paths resolve against",
        "`BLITZE_PROJECT_DIR` (default: the working directory).",
        "",
        "## Settings",
        "",
        _table(["Environment variable", "TOML key", "Default", "Constraints"], rows),
        "## Secrets",
        "",
        "Secrets are deliberately not valid TOML keys — they are environment-only.",
        "",
        _table(
            ["Environment variable", "Notes"],
            [
                [
                    "`BLITZE_API_KEYS`",
                    "Comma-separated `operator:secret`. Each secret needs ≥ 32 "
                    "characters. Duplicate operators are rejected.",
                ],
                [
                    "`BLITZE_API_KEY`",
                    "Single unnamed key, registered as operator `default`. "
                    "Also ≥ 32 characters.",
                ],
            ],
        ),
        "## Other variables read at startup",
        "",
        _table(
            ["Environment variable"],
            [[_cell(name)] for name in sorted(set(bare) - documented)],
        ),
    ]
    return "\n".join(lines)


