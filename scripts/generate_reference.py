def main() -> int:
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument(
        "--check",
        action="store_true",
        help="Fail instead of writing when the committed output is stale.",
    )
    arguments = parser.parse_args()

    pages = {
        "api.mdx": render_api(build_openapi_schema()),
        "cli.mdx": render_cli(),
        "configuration.mdx": render_configuration(),
        "roles.mdx": render_roles(),
    }

    OUTPUT_DIR.mkdir(parents=True, exist_ok=True)
    stale: list[str] = []
    for name, content in pages.items():
        target = OUTPUT_DIR / name
        current = target.read_text(encoding="utf-8") if target.is_file() else None
        if current == content:
            continue
        if arguments.check:
            stale.append(name)
        else:
            target.write_text(content, encoding="utf-8")
            print(f"wrote {target.relative_to(WEB_DIR)}")

    if stale:
        print(
            "Generated reference is stale: "
            + ", ".join(stale)
            + "\nRun `npm run generate` in web/ and commit the result.",
            file=sys.stderr,
        )
        return 1
    if arguments.check:
        print("Generated reference is current.")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
