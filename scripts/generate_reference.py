#!/usr/bin/env python
"""Generate the reference section of the docs site from its two sources.

Every page this writes restates facts that already exist in machine-readable
form — the OpenAPI schema, the Typer command tree, ``Settings.from_environment``
and each role's ``argument_specs.yml``. Generating them means they cannot drift;
``--check`` fails CI when the committed output no longer matches those sources.

Both sources live in other repositories, so this documents whichever versions
are installed:

* the control plane comes from the installed ``blitzecdn`` distribution
  (``requirements.txt``);
* the edge roles come from the installed ``blitzecdn.edge`` collection
  (``requirements.yml``).

Point ``BLITZECDN_EDGE_COLLECTION`` at a checkout to preview unreleased role
changes. A sibling ``../blitze-cdn-edge`` checkout is picked up automatically
as a development convenience.

Nothing here may read real controller state. The API generator builds the app
against a throwaway ``Settings`` in a temporary directory, because
``create_app()`` with no arguments would call ``Settings.from_environment()``
and open the operator's real SQLite database as a side effect.
"""

from __future__ import annotations

import argparse
import ast
import json
import os
import tempfile
from pathlib import Path
from typing import Any

import yaml

WEB_DIR = Path(__file__).resolve().parent.parent
OUTPUT_DIR = WEB_DIR / "src/content/reference"

BANNER = (
    "{/* Generated by scripts/generate_reference.py. Do not edit by hand;\n"
    "    run `npm run generate` after upgrading blitzecdn or blitzecdn.edge. */}\n"
)


def _control_plane_source() -> Path:
    """Locate config.py in the installed control plane, for the AST walk."""
    from blitzecdn import config

    return Path(config.__file__)


def _edge_roles_dir() -> Path:
    """Locate roles/ of the edge collection this site documents."""
    override = os.environ.get("BLITZECDN_EDGE_COLLECTION")
    candidates = [Path(override)] if override else []
    candidates += [
        WEB_DIR / ".state/collections/ansible_collections/blitzecdn/edge",
        Path.home() / ".ansible/collections/ansible_collections/blitzecdn/edge",
        Path("/usr/share/ansible/collections/ansible_collections/blitzecdn/edge"),
        # Development convenience: a sibling checkout of the edge repository.
        WEB_DIR.parent / "blitze-cdn-edge",
    ]
    for candidate in candidates:
        if (candidate / "roles").is_dir():
            return candidate / "roles"
    raise SystemExit(
        "Cannot find the blitzecdn.edge collection. Install it with\n"
        "  ansible-galaxy collection install -r requirements.yml "
        "-p .state/collections\n"
        "or set BLITZECDN_EDGE_COLLECTION to a checkout."
    )


# --------------------------------------------------------------------------
# helpers
# --------------------------------------------------------------------------


def _text(value: object) -> str:
    """Escape free prose for MDX.

    MDX reads `{...}` as a JavaScript expression and `<` as a JSX tag, so a
    docstring mentioning `/v1/deployments/{id}` becomes `id is not defined` at
    build time. Values rendered inside backticks by `_cell` are already safe.
    """
    if value is None:
        return ""
    return (
        str(value)
        .replace("{", "\\{")
        .replace("}", "\\}")
        .replace("<", "\\<")
    )


def _cell(value: object) -> str:
    """Render a value for a Markdown table cell."""
    if value is None or value == "":
        return "—"
    if isinstance(value, bool):
        return "`true`" if value else "`false`"
    if isinstance(value, (list, tuple)):
        return ", ".join(f"`{item}`" for item in value) if value else "—"
    text = str(value).replace("|", "\\|").replace("\n", " ")
    return f"`{text}`"


def _table(headers: list[str], rows: list[list[str]]) -> str:
    if not rows:
        return "_None._\n"
    out = ["| " + " | ".join(headers) + " |"]
    out.append("| " + " | ".join("---" for _ in headers) + " |")
    out.extend("| " + " | ".join(row) + " |" for row in rows)
    return "\n".join(out) + "\n"


def _schema_name(schema: dict[str, Any]) -> str:
    """Best-effort one-line type description for an OpenAPI schema node."""
    if "$ref" in schema:
        return schema["$ref"].rsplit("/", 1)[-1]
    if "anyOf" in schema:
        return " \\| ".join(_schema_name(item) for item in schema["anyOf"])
    if "allOf" in schema:
        return " & ".join(_schema_name(item) for item in schema["allOf"])
    kind = schema.get("type", "object")
    if kind == "array":
        return f"{_schema_name(schema.get('items', {}))}[]"
    if "enum" in schema:
        return " \\| ".join(json.dumps(value) for value in schema["enum"])
    return str(kind)


