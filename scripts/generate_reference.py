def _render_params(params: list[Any]) -> str:
    rows = []
    for param in params:
        if param.name == "help" or getattr(param, "hidden", False):
            continue
        flags = ", ".join(param.opts + param.secondary_opts) or param.name
        default = param.default
        if default in (None, False):
            default = None
        rows.append(
            [
                _cell(flags),
                _cell(getattr(param.type, "name", "text")),
                _cell(bool(param.required)),
                _cell(default),
                _text(getattr(param, "help", None) or "—").replace("\n", " "),
            ]
        )
    return _table(["Flag", "Type", "Required", "Default", "Description"], rows)


def render_cli() -> str:
    import click
    import typer.main

    from blitzecdn.cli import ExitCode, app

    root = typer.main.get_command(app)

    lines = [
        BANNER,
        "# CLI",
        "",
        "Generated from the Typer command tree in `src/blitzecdn/cli.py`.",
        "",
        "## Exit codes",
        "",
        _table(
            ["Code", "Meaning"],
            [[_cell(item.value), item.name.replace("_", " ").title()]
             for item in ExitCode],
        ),
        "## Global options",
        "",
        _render_params(root.params),
    ]

    def emit(command: Any, prefix: str) -> None:
        for name, sub in sorted(getattr(command, "commands", {}).items()):
            full = f"{prefix} {name}".strip()
            lines.append(f"## `{full}`")
            lines.append("")
            helptext = (sub.help or sub.short_help or "").strip()
            if helptext:
                lines.extend([_text(helptext), ""])
            lines.append(_render_params(sub.params))
            if isinstance(sub, click.Group):
                emit(sub, full)

    emit(root, "blitzecdn")
    return "\n".join(lines)


